.syntax unified
.arm

.macro OPAQUE_ADDRESS_RETURN name, identity
    .section .text.\name,"ax",%progbits
    .balign 4
    .global \name
    .type \name, %function
\name:
    ldr r0, .Lliteral_\name
    bx lr
    .size \name, .-\name
.Lliteral_\name:
    .word \identity
    .global \identity
.endm

